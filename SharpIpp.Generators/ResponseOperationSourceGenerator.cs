using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace SharpIpp.Generators;

/// <summary>
/// Incremental source generator that discovers classes annotated with <c>[IppResponse(IppOperation)]</c>
/// implementing <c>IIppResponse</c> and generates compile-time pattern matching in <c>IppResponseExtensions.GetOperation</c>.
/// </summary>
[Generator]
public class ResponseOperationSourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => s is ClassDeclarationSyntax,
                transform: static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) as INamedTypeSymbol)
            .Where(static s => s != null)
            .Select(static (s, _) => s!);

        var compilationAndClasses = context.CompilationProvider.Combine(classDeclarations.Collect());

        context.RegisterSourceOutput(compilationAndClasses, static (spc, source) =>
        {
            Execute(source.Left, source.Right, spc);
        });
    }

    internal static void Execute(Compilation compilation, ImmutableArray<INamedTypeSymbol> classes, SourceProductionContext context)
    {
        var ippResponseAttrSymbol = compilation.GetTypeByMetadataName("SharpIpp.Mapping.IppResponseAttribute");
        if (ippResponseAttrSymbol == null)
            return;

        var iIppResponseSymbol = compilation.GetTypeByMetadataName("SharpIpp.Protocol.IIppResponse");
        if (iIppResponseSymbol == null)
            return;

        var entries = new List<(INamedTypeSymbol Type, string OperationExpr)>();

        foreach (var typeSymbol in classes)
        {
            if (typeSymbol.IsAbstract || typeSymbol.IsStatic || typeSymbol.TypeKind != TypeKind.Class || typeSymbol.IsGenericType)
                continue;

            if (!ImplementsOrInherits(typeSymbol, iIppResponseSymbol))
                continue;

            var attr = GetAttribute(typeSymbol, ippResponseAttrSymbol);
            if (attr == null || attr.ConstructorArguments.Length == 0)
                continue;

            var val = attr.ConstructorArguments[0].Value;
            if (val == null)
                continue;

            var enumType = attr.ConstructorArguments[0].Type;
            var fieldName = TryGetEnumFieldName(enumType, val);
            string opExpr = fieldName != null
                ? $"global::SharpIpp.Protocol.Models.IppOperation.{fieldName}"
                : $"(global::SharpIpp.Protocol.Models.IppOperation){val}";

            entries.Add((typeSymbol, opExpr));
        }

        // Order descending by inheritance depth, then by fully qualified type name
        var sortedEntries = entries
            .OrderByDescending(e => GetInheritanceDepth(e.Type))
            .ThenBy(e => e.Type.ToDisplayString())
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace SharpIpp.Protocol.Extensions;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Provides static, AOT-friendly resolution of <see cref=\"global::SharpIpp.Protocol.Models.IppOperation\"/> from response types without reflection.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class IppResponseExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Gets the <see cref=\"global::SharpIpp.Protocol.Models.IppOperation\"/> associated with the given response model using compile-time pattern matching.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <param name=\"response\">The response instance.</param>");
        sb.AppendLine("    /// <returns>The associated <see cref=\"global::SharpIpp.Protocol.Models.IppOperation\"/>, or <c>null</c> if not recognized.</returns>");
        sb.AppendLine("    public static global::SharpIpp.Protocol.Models.IppOperation? GetOperation(this global::SharpIpp.Protocol.IIppResponse? response) => response switch");
        sb.AppendLine("    {");

        foreach (var (type, opExpr) in sortedEntries)
        {
            var fqn = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            sb.AppendLine($"        {fqn} => {opExpr},");
        }

        sb.AppendLine("        _ => null,");
        sb.AppendLine("    };");
        sb.AppendLine("}");

        context.AddSource("IppResponseExtensions.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    internal static AttributeData? GetAttribute(INamedTypeSymbol? typeSymbol, INamedTypeSymbol? attrSymbol)
    {
        if (typeSymbol == null || attrSymbol == null)
            return null;

        return typeSymbol.GetAttributes().FirstOrDefault(attr => SymbolEqualityComparer.Default.Equals(attr.AttributeClass, attrSymbol));
    }

    internal static bool ImplementsOrInherits(ITypeSymbol? symbol, ITypeSymbol? targetType)
    {
        if (symbol == null || targetType == null)
            return false;

        if (SymbolEqualityComparer.Default.Equals(symbol, targetType))
            return true;

        if (targetType.TypeKind == TypeKind.Interface)
        {
            foreach (var iface in symbol.AllInterfaces)
            {
                if (SymbolEqualityComparer.Default.Equals(iface, targetType))
                    return true;
            }
        }
        else
        {
            var curr = symbol.BaseType;
            while (curr != null)
            {
                if (SymbolEqualityComparer.Default.Equals(curr, targetType))
                    return true;
                curr = curr.BaseType;
            }
        }

        return false;
    }

    internal static int GetInheritanceDepth(INamedTypeSymbol type)
    {
        int depth = 0;
        var curr = type.BaseType;
        while (curr != null && curr.SpecialType != SpecialType.System_Object)
        {
            depth++;
            curr = curr.BaseType;
        }
        return depth;
    }

    internal static string? TryGetEnumFieldName(ITypeSymbol? type, object? value)
    {
        if (type is not INamedTypeSymbol { TypeKind: TypeKind.Enum } enumType || value == null)
            return null;

        foreach (var member in enumType.GetMembers())
        {
            if (member is IFieldSymbol { HasConstantValue: true } field && Equals(field.ConstantValue, value))
                return field.Name;
        }
        return null;
    }
}

